#!/usr/bin/env bash
# Builds supabase/setup-dev.sql: every migration plus the sample seed in one file, for pasting
# into the Supabase dashboard's SQL Editor (no CLI needed). It also records the migrations as
# applied, so a later `supabase db push` only runs migrations added after this file.
# Run again whenever a migration is added.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup-dev.sql
{
  echo "-- GENERATED by scripts/build-dev-setup-sql.sh. Do not edit by hand."
  echo "-- Development project only: includes sample seed data. Paste into Supabase → SQL Editor → Run."
  echo
  for f in supabase/migrations/*.sql; do
    echo "-- ============================================================"
    echo "-- $(basename "$f")"
    echo "-- ============================================================"
    cat "$f"
    echo
  done
  echo "-- ============================================================"
  echo "-- seed.sql (sample data, development only)"
  echo "-- ============================================================"
  cat supabase/seed.sql
  echo
  echo "-- Record the migrations as applied, so the Supabase CLI does not run them again."
  echo "create schema if not exists supabase_migrations;"
  echo "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);"
  echo "insert into supabase_migrations.schema_migrations (version, name) values"
  first=1
  for f in supabase/migrations/*.sql; do
    base=$(basename "$f" .sql)
    [ $first -eq 1 ] && first=0 || echo ","
    printf "  ('%s', '%s')" "${base%%_*}" "${base#*_}"
  done
  echo
  echo "on conflict (version) do nothing;"
  echo
  echo "select 'Ghana Transport database is ready: ' || (select count(*) from public.stations) || ' stations, ' || (select count(*) from public.fares) || ' fares' as result;"
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
